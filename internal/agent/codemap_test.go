// Vu en réel (ticket "Ajouter un filtre sur les documents") : l'agent a
// cherché l'onglet Documents dans internal/store (le stockage sur disque
// de la CLI) faute de savoir où vit l'interface web. La carte du code lui
// donne chaque paquet et son rôle, lus dans le commentaire de paquet.
func TestPackageMap_ListsPackagesWithTheirRole(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"go.mod":                          "module example.com/app\n",
		"cmd/app/main.go":                 "// Command app est l'application web : upload et suivi de documents.\npackage main\n",
		"internal/webapp/jobs.go":         "// Package webapp orchestre le pipeline pour l'interface web. Suite ignorée.\npackage webapp\n",
		"internal/webapp/jobs_test.go":    "// Package webapp (tests) : ne doit pas servir de description.\npackage webapp\n",
		"internal/store/store.go":         "// Package store persiste les résultats sur disque, un JSON par page, avec une description beaucoup trop longue pour tenir sur une ligne de la carte.\npackage store\n",
		"internal/nodoc/x.go":             "package nodoc\n",
		"cmd/app/templates/page.templ":    "package templates\n",
		"cmd/app/templates/page_templ.go": "// Code generated by templ - DO NOT EDIT.\n\n// templ: version: v0.3\npackage templates\n",
		"testdata/fixtures/x.go":          "// Package fixtures ne doit pas apparaître.\npackage fixtures\n",
		".git/hooks/x.go":                 "package hooks\n",
	}
	for name, content := range files {
		p := filepath.Join(root, name)
		os.MkdirAll(filepath.Dir(p), 0o755)
		os.WriteFile(p, []byte(content), 0o644)
	}

	got := PackageMap(root, 2500)
	for _, want := range []string{
		"cmd/app — l'application web : upload et suivi de documents",
		"internal/webapp — orchestre le pipeline pour l'interface web",
		"internal/nodoc",
		"cmd/app/templates — gabarits templ des pages web",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("map lacks %q:\n%s", want, got)
		}
	}
	for _, unwanted := range []string{"Suite ignorée", "tests", "fixtures", "hooks", "templ: version", "trop longue pour tenir sur une ligne de la carte"} {
		if strings.Contains(got, unwanted) {
			t.Errorf("map contains %q:\n%s", unwanted, got)
		}
	}
	if len(PackageMap(root, 120)) > 120 {
		t.Error("map exceeds its budget")
	}
}

// La carte est donnée aux deux agents des tickets, après les consignes.
func TestSystemPrompts_IncludeCodeMap(t *testing.T) {
	a := &Analyzer{CodeMap: "internal/webapp — interface web"}
	d := &Developer{CodeMap: "internal/webapp — interface web"}
	for name, p := range map[string]string{"analyse": a.systemPrompt(), "développement": d.systemPrompt()} {
		if !strings.Contains(p, "Carte du code") || !strings.Contains(p, "internal/webapp — interface web") {
			t.Errorf("%s: system prompt lacks the code map:\n%s", name, p)
		}
	}
}

// Budget serré : chaque paquet reste listé (descriptions raccourcies),
// plutôt que les derniers dans l'ordre alphabétique disparaissent — vu
// sur le vrai dépôt, internal/webapp était coupé. Les mentions de jalon
// n'apprennent rien à l'agent.
func TestPackageMap_TightBudgetKeepsEveryPackage(t *testing.T) {
	root := t.TempDir()
	for _, name := range []string{"a", "b", "c", "d", "webapp"} {
		p := filepath.Join(root, "internal", name, "x.go")
		os.MkdirAll(filepath.Dir(p), 0o755)
		os.WriteFile(p, []byte("// Package "+name+" fait quelque chose d'utile (jalon 12 : détail) avec une description plutôt longue pour ce paquet.\npackage "+name+"\n"), 0o644)
	}
	got := PackageMap(root, 300)
	if len(got) > 300 {
		t.Errorf("map = %d chars, budget 300", len(got))
	}
	for _, name := range []string{"a", "b", "c", "d", "webapp"} {
		if !strings.Contains(got, "internal/"+name) {
			t.Errorf("internal/%s dropped:\n%s", name, got)
		}
	}
	if strings.Contains(got, "jalon") {
		t.Errorf("milestone mention kept:\n%s", got)
	}
}

// « (cf. x) » coupe la première phrase au milieu d'une parenthèse : la
// parenthèse ouverte est retirée.
func TestPackageMap_NoDanglingParenthesis(t *testing.T) {
	root := t.TempDir()
	p := filepath.Join(root, "internal", "parsing", "x.go")
	os.MkdirAll(filepath.Dir(p), 0o755)
	os.WriteFile(p, []byte("// Package parsing lit les pages sans texte fiable (cf. triage) avec le VLM.\npackage parsing\n"), 0o644)
	if got := PackageMap(root, 500); got != "internal/parsing — lit les pages sans texte fiable" {
		t.Errorf("map = %q", got)
	}
}
